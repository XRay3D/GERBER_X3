#pragma once

#include "geo/polygon.h"
#include "geo/polyline.h"

#include <vector>

namespace Geo {

// Витки офсета области, разложенные ПО ФИГУРАМ.
//
// Виток d монолитного Inflate(area, -2d) для области «объемлющее минус
// тела» считается по морфологическому тождеству
//
//     erosion(A \ B, d) = erosion(A, d) \ dilation(B, d),
//
// где A -- объединение объемлющих контуров (addAmbient), B -- объединение
// тел (addSolid): каждый источник офсетится НЕЗАВИСИМО, в своём потоке и
// на своих объектах, а виток собирается объединением готовых кусков и
// одной разностью. Без объемлющих виток -- просто объединение раздутых
// тел (карман фиксированных шагов наружу).
//
// Зачем так: у монолитного витка капсулы строятся по ВСЕЙ границе области
// разом, их объединение и итоговая разность ворочают всю плату целиком, а
// база витков упрощается только когда упростилась ВСЯ область -- на
// практике с дюжины витка (см. plugins/gcode/pocketoffset). Пофигурно же
// каждый источник мал, его витки сглаживаются за один-два прохода (пятачок
// становится окружностью), и принятая пофигурная база рубит цену ранних
// витков -- тех самых, где монолиту зацепиться не за что.
//
// Сам по себе пофигурный виток НЕ дешевле монолитного: объединение клякс --
// та же работа CGAL, что объединение капсул границы, и в середине кармана
// они идут вровень. Выигрыш дают три упрощения поверх него, у монолита
// невозможные: слившиеся кляксы группы ПРИНИМАЮТСЯ базой разом (полтысячи
// пятачков -- в десяток клякс за несколько витков) и при этом ОТСЕКАЮТСЯ по
// усаженному объемлющему (наружная сторона меди полю не нужна, а клякса вне
// усаженного объемлющего не повлияет уже ни на один виток -- объемлющее
// усаживается с той же скоростью, с какой она растёт); тело, чей габарит
// объемлющего больше не достаёт, умирает; а группа, где тел осталась
// горстка, СХЛОПЫВАЕТСЯ: её поле становится её объемлющим, и дальше она
// усаживается как монолит от простой базы -- это и есть дешёвый хвост.
// Замер на coldfire-плате (фреза 0.5 мм, одна сборка): слой VDD 11.7 ->
// 8.6 с, Top 15.9 -> 13.4 с; выигрыш -- ранние витки, хвост на равных.
//
// Потокобезопасность -- ПО ПОСТРОЕНИЮ, а не синхронизацией: база каждого
// источника пересобирается из bulge-вида ещё при добавлении, так что общих
// точных чисел и ленивых кэшей (Polygons::Impl::view -- см. провал
// параллельных витков в pocketoffset) у источников нет вовсе. Источник,
// чья пересборка потеряла контур (вырожденная дырка), офсетится от точной
// копии тела ПОСЛЕДОВАТЕЛЬНО в вызывающем потоке.
//
// Черновой допуск coarse наследует контракт Inflate: недобор каждой
// пофигурной полосы направлен К СВОЕЙ границе, поэтому объединение тел --
// подмножество честного, усадка объемлющего -- надмножество, и контур
// витка уезжает только К границе области. На свежей базе -- не дальше
// coarse; принятая база сама черновая, и её недобор ПЕРЕХОДИТ в следующие
// витки -- ровно как у монолитных витков, где базой тоже становится
// черновая петля. Копится он по числу ПРИНЯТИЙ, а не витков (принятие
// требует строгого упрощения, и пятачок, став окружностью, больше не
// принимается), а расстояние между соседними витками держится в пределах
// шаг ± coarse при любой истории принятий -- гребешка и зареза дрейф не
// даёт.
class InflatePasses {
public:
    InflatePasses();
    ~InflatePasses();
    InflatePasses(InflatePasses&&) noexcept;
    InflatePasses& operator=(InflatePasses&&) noexcept;

    // Тело ОБЛАСТИ целиком: его внешний контур усаживается, каждая его
    // дырка раздувается сама по себе, и виток тела -- усаженный контур минус
    // объединение раздутых дырок. Вложенные тела области (поле внутри
    // медного кластера, который сам лежит в поле) -- отдельные тела: дырка
    // одного -- ОБОЛОЧКА другого, и вычитать её из всех разом нельзя.
    // Возвращает номер группы тела -- для тел, которые надо вычитать только
    // из него (см. addSolid).
    std::size_t addField(const Polygon& body);

    // То же по частям: объемлющий контур (обход против часовой стрелки)
    // открывает группу, тела с её номером вычитаются только из неё.
    std::size_t addAmbient(const Polyline& contour);

    // Тело без группы -- ГЛОБАЛЬНОЕ: вычитается из всей области; без
    // объемлющих вовсе виток -- объединение таких тел (карман фиксированных
    // шагов наружу). На витке pass(d) тело раздувается на полуширину
    // d + bias; сдвиг bias < 0 -- для областей, запретных с самого начала
    // (полоса контурного прохода кармана): на первом витке они вычитаются
    // как есть, дальше растут шагом витков.
    static constexpr std::size_t global = static_cast<std::size_t>(-1);
    void addSolid(const Polygon& body, std::size_t group = global, double bias = 0.0);
    void addSolid(const Polyline& contour, std::size_t group = global, double bias = 0.0);
    void addSolids(const Polygons& region, std::size_t group = global, double bias = 0.0);

    // Регион витка: ⋃ₖ [erosion(ambientₖ, d) − ⋃ dilation(solidₖ, d + bias)]
    // − ⋃ dilation(global, d + bias). Без объемлющих -- объединение раздутых
    // глобальных тел. Пустой регион -- область кончилась (все объемлющие
    // съедены усадкой); с одними телами без объемлющих пустым он не бывает,
    // остановка -- за вызывающим.
    Polygons pass(double d, double coarse = 0.0);
    // То же по компонентам -- разнесённым регионам, без их сборки в один
    // (pass() собирает их через Polygons::fromSeparated). Пустой список --
    // область кончилась.
    std::vector<Polygons> passParts(double d, double coarse = 0.0);

private:
    struct Source;
    std::vector<Source> solids_, ambients_;
};

} // namespace Geo
