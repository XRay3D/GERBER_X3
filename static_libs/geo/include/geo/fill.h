#pragma once

// Заполнение региона строками -- то, что растровые стратегии (выборка,
// штриховка) делают поверх булевых операций. Живёт отдельно от boolean.h:
// это не операция над регионом, а ГОТОВАЯ ТРАЕКТОРИЯ по нему.

#include "geo/polygon.h"
#include "geo/polyline.h"

namespace Geo {

// Змейка (боустрофедон): регион покрывается горизонтальными строками через
// `step`, и строки сшиваются в непрерывные проходы -- там, где строка
// упирается в границу, путь продолжается КУСКОМ ГРАНИЦЫ до соседней строки
// и идёт по ней обратно. Прежде это же собиралось Clipper2-ом в каждом
// растровом плагине по отдельности; резка здесь -- Geo::clipOpen.
//
// `angle` (ГРАДУСЫ, как и везде в Qt) поворачивает штриховку: регион
// подставляется ПОД горизонтальную змейку, результат поворачивается
// обратно; центр поворота -- начало координат, на форму заполнения он не
// влияет.
//
// Куски сшиваются по совпадению концов в пределах exitWeldTolerance: точки
// разреза считаются в double, бит-в-бит они не сходятся. Пустой регион даёт
// пустой список; шаг шире региона -- одну строку посередине, а не пустоту.
Polylines zigzagFill(const Polygons& region, double step, double angle = 0.0);

} // namespace Geo
