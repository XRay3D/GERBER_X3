#pragma once

// Отмена долгих вычислений.
//
// Отмена здесь ОБЛАСТНАЯ, а не параметр каждой функции: она объявляется
// объектом CancelScope на время его жизни и действует на все операции Geo
// в этом потоке. Так сделано потому, что параметром её не протащить --
// composite-операции региона (`region |= other`) лишнего аргумента не
// принимают вовсе, а протаскивание токена через каждую перегрузку Inflate
// и BooleanOp раздуло бы API вчетверо ради того, что почти всегда пусто.
//
// Прерванная операция БРОСАЕТ Cancelled. Возврат «пустого» результата не
// годится: пустой регион -- законный ответ, и вызывающий не отличил бы
// прерванное вычисление от честно посчитанной пустоты, а промежуточные
// стадии конвейера молча считали бы дальше по мусору.
//
// Отмена КООПЕРАТИВНА и срабатывает на границах единиц работы: между
// контурами в parallelFor, между кусками дерева слияний в joinAll, между
// полилиниями в ArcRecovery. Одиночный точный свип CGAL внутрь себя
// заглянуть не даёт, так что отклик ограничен самой долгой такой
// единицей -- на практике это слияние двух крупных кусков региона.
//
// Стоп-токен -- обычный std::stop_token из C++20: ничего сверх него здесь
// не нужно, а рабочие потоки Geo и так std::jthread.

#include <exception>
#include <stop_token>

namespace Geo {

// Брошено операцией Geo, прерванной по запросу отмены.
class Cancelled : public std::exception {
public:
    const char* what() const noexcept override;
};

// Объявляет `token` признаком отмены для операций Geo в ТЕКУЩЕМ потоке --
// на время своей жизни. Области вкладываются: деструктор возвращает ту,
// что действовала раньше.
//
// Рабочие потоки самой Geo область наследуют (parallelFor и joinAll
// ставят её себе сами), а вот сторонний поток -- нет: у него свой
// thread_local, и токен туда нужно занести таким же CancelScope.
class CancelScope {
public:
    explicit CancelScope(std::stop_token token) noexcept;
    ~CancelScope();

    CancelScope(const CancelScope&) = delete;
    CancelScope& operator=(const CancelScope&) = delete;

private:
    std::stop_token previous_;
};

// Токен действующей области; пустой (stop_possible() == false), когда
// области нет. Нужен, чтобы передать отмену в свой рабочий поток.
std::stop_token cancelToken() noexcept;

// Запрошена ли отмена. Вне всякой области -- всегда false, так что
// вызывающий, которому отмена не нужна, ничего о ней и не узнает.
bool cancelRequested() noexcept;

// То же, но сразу бросает Cancelled. Ставится в циклах по единицам
// работы -- там, где прерваться безопасно.
void checkCancelled();

} // namespace Geo
