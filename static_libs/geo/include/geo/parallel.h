#pragma once

// Параллельный обход [0, count) рабочими потоками библиотеки: body(i)
// вызывается ровно раз для каждого i, в неопределённом порядке и из разных
// потоков. Тело обязано писать только в СВОЮ ячейку общих данных --
// синхронизации здесь нет никакой.
//
// Это тот же цикл, которым Geo параллелит собственные операции (перевод
// контуров, дерево слияний, InflateSeries), вынесенный наружу для
// вызывающих с независимыми по элементам задачами -- например, подготовка
// областей кармана по телам. Пользоваться им, а не своими потоками, стоит
// из-за двух его свойств:
//
//   * токен отмены (cancel.h) заносится в рабочие потоки сам, и отмена
//     внутри тела приходит исключением, как у всякой операции Geo;
//   * вложенный parallelFor внутри тела не плодит второй ярус потоков --
//     идёт на месте (дерево слияний joinAll при этом потоки держит: у
//     кривых по размеру задач внешнего уровня оно одно и спасает).
//
// minBatch -- нижняя граница «элементов на поток», ниже которой цикл идёт
// на месте: запуск потока стоит десятки микросекунд. Умолчание 1 --
// публичный вызывающий приходит сюда с телами, каждое из которых заведомо
// дороже потока (офсет региона, а не перевод одного контура).

#include <cstddef>
#include <functional>

namespace Geo {

void parallelFor(std::size_t count, const std::function<void(std::size_t)>& body,
    std::size_t minBatch = 1);

} // namespace Geo
