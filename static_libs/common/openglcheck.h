#pragma once

#include <QCommandLineOption>
#include <QString>

/* Проверка OpenGL до создания первого GL-виджета.
 *
 * Зачем: на Windows с битым/древним драйвером видеокарты приложение падало или
 * зависало прямо на старте — QOpenGLWidget создаётся ещё в конструкторе
 * GraphicsView, до появления окна, так что пользователь не видел даже причины.
 *
 * Как это работает - два рубежа:
 *
 * 1. Закадровая проверка (probe): создаём QOpenGLContext + QOffscreenSurface и
 *    делаем контекст текущим. Если драйвер GL не отдаёт вовсе или отдаёт
 *    непригодный (< 2.0), GL выключается на весь сеанс, а виджеты работают
 *    через обычный растровый вывод.
 *
 * 2. Маркер незавершённого старта (safe mode): если драйвер не возвращает
 *    управление, а роняет процесс, проверка из п.1 не поможет — падение
 *    случается внутри неё. Поэтому перед инициализацией GL на диск кладётся
 *    файл-маркер, который снимается, когда окно уже отрисовалось. Найденный на
 *    старте маркер означает "прошлый запуск не пережил инициализацию", и режим
 *    понижается: Auto/Desktop -> Software -> Off. Если и Off не завёлся, дело
 *    не в GL: режим сбрасывается обратно в Auto, чтобы не деградировать вечно.
 *
 * Ручное управление (перебивает safe mode):
 *   GGEASY_OPENGL=auto|desktop|software|off
 *   GGEasy --opengl=software
 */
namespace OpenGlCheck {

enum class Mode {
    Auto,     // железный GL, при неудаче -- откат на растр
    Desktop,  // принудительно железный
    Software, // принудительно программный (Mesa llvmpipe / opengl32sw.dll)
    Off,      // GL не трогать вовсе
};

// Ключ --opengl. Здесь же, а не в main, чтобы имя и описание были в одном
// месте: selectMode разбирает его своим парсером до QApplication, а общему
// парсеру приложения его всё равно надо объявить -- иначе process() отвергнет
// ключ как неизвестный.
QCommandLineOption commandLineOption();

// Вызывать ДО создания QApplication (атрибуты Qt::AA_Use*OpenGL и QT_OPENGL
// читаются при её конструировании). Требует уже выставленных
// QCoreApplication::setOrganizationName/setApplicationName -- по ним ищется
// каталог для маркера.
void selectMode(int argc, char** argv);

// Вызывать ПОСЛЕ создания QApplication и ДО первого QOpenGLWidget.
void probe();

// Можно ли создавать GL-виджеты в этом сеансе.
bool available();

Mode mode();

// Человекочитаемо: какой режим выбран, что сказал драйвер, почему GL выключен.
// Для лога и вкладки настроек.
QString report();

// Почему ускорения нет и как его вернуть -- для окна логов и для 3D-панели.
// Пусто, когда ускорение работает.
QString howToEnable();

// Написать состояние графики в лог приложения. Вызывать, когда главное окно
// уже создано: сообщения из selectMode и probe до него не доходят -- окна с
// логом на тот момент ещё нет, и человек причины не видит.
void logStatus();

// Снять маркер незавершённого старта. Вызывать, когда окно уже отрисовалось.
void markStartupSucceeded();

} // namespace OpenGlCheck
